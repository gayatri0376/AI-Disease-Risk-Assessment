"""
predictor.py — Core ML Prediction Service Module
=================================================
AI-Based Anemia Screening and Blood Report Interpretation System
College Project — Educational Use Only (Not Clinically Validated)

PURPOSE:
--------
Loads saved, audited scikit-learn model pipelines and metadata from `ml_model/models/`
and executes robust inference for:
  1. `predict_anemia_screening(cbc_values, scenario="scenario_2", model_name="random_forest")`
     (Task B: Binary Anemia Screening — Healthy vs. Anemia Subtypes)
  2. `predict_diagnosis(cbc_values, scenario="scenario_2", model_name="random_forest")`
     (Task A: 9-Class Multiclass Classification — Specific Blood Disorder Subtypes)

DESIGN PRINCIPLES:
------------------
  • Scenarios supported: 'scenario_1' / 'scenario1' (primary), 'scenario_2' / 'scenario2' (default).
  • Default model: 'random_forest' (highest generalization score in Phase 5 benchmark).
  • Models available: 'logistic_regression', 'decision_tree', 'random_forest'.
  • Exact metadata-driven threshold application for Task B.
  • Strict separation of input validation from preprocessing.
  • Prominent clinical safety disclaimer on all prediction outputs.
"""

import sys
import json
import joblib
from pathlib import Path
from typing import Dict, Any, Optional

import numpy as np
import pandas as pd

# Path setup relative to project root
THIS_FILE = Path(__file__).resolve()
BACKEND_DIR = THIS_FILE.parents[2]
PROJECT_ROOT = BACKEND_DIR.parent
ML_MODELS_DIR = PROJECT_ROOT / "ml_model" / "models"
METADATA_PATH = ML_MODELS_DIR / "model_metadata.json"

# Import input validation
from backend.apps.ml_service.validators import (
    validate_cbc_input,
    EXPECTED_FEATURES,
    ValidationError,
)

# Standardized educational disclaimer
CLINICAL_DISCLAIMER: str = (
    "DISCLAIMER: This prediction is generated by an academic machine-learning model "
    "for educational and screening demonstration purposes only. It is NOT clinically validated, "
    "does NOT constitute a medical diagnosis, and must NOT be used for patient care decisions. "
    "Consult a qualified healthcare professional or laboratory physician for proper medical interpretation."
)

# Supported configuration aliases
VALID_SCENARIOS = {
    "scenario_1": "scenario1",
    "scenario1": "scenario1",
    "scenario_2": "scenario2",
    "scenario2": "scenario2",
}

VALID_MODELS = {
    "logistic_regression",
    "decision_tree",
    "random_forest",
}

# Task B Human-readable label mapping
TASK_B_LABEL_MAPPING = {
    0: "Healthy (Non-Anemic)",
    1: "Anemia Detected (Requires Clinical Follow-up)",
}

# In-memory pipeline and metadata cache for fast repeated inference
_MODEL_CACHE: Dict[str, Any] = {}
_METADATA_CACHE: Optional[Dict[str, Any]] = None


def get_model_metadata() -> Dict[str, Any]:
    """Load and cache model_metadata.json."""
    global _METADATA_CACHE
    if _METADATA_CACHE is None:
        if not METADATA_PATH.exists():
            raise FileNotFoundError(
                f"Model metadata file not found at: {METADATA_PATH}. "
                f"Ensure Phase 5 model training has been executed."
            )
        with open(METADATA_PATH, "r", encoding="utf-8") as f:
            _METADATA_CACHE = json.load(f)
    return _METADATA_CACHE


def load_pipeline(task: str, scenario: str, model_name: str):
    """
    Load and cache a serialized scikit-learn pipeline from ml_model/models/.

    Parameters
    ----------
    task : str
        'task_a' or 'task_b'
    scenario : str
        'scenario1' or 'scenario2'
    model_name : str
        'logistic_regression', 'decision_tree', or 'random_forest'
    """
    model_key = f"{task}_{scenario}_{model_name}"
    if model_key not in _MODEL_CACHE:
        model_file = ML_MODELS_DIR / f"{model_key}.joblib"
        if not model_file.exists():
            raise FileNotFoundError(
                f"Trained model pipeline not found at: {model_file}. "
                f"Verify that model file exists in {ML_MODELS_DIR}."
            )
        _MODEL_CACHE[model_key] = joblib.load(model_file)
    return _MODEL_CACHE[model_key]


def _normalize_config(scenario: str, model_name: str) -> tuple[str, str]:
    """Normalize and validate scenario and model_name arguments."""
    norm_scenario = str(scenario).strip().lower()
    if norm_scenario not in VALID_SCENARIOS:
        raise ValueError(
            f"Invalid scenario '{scenario}'. Permissible options: "
            f"{sorted(list(VALID_SCENARIOS.keys()))}."
        )
    canonical_scenario = VALID_SCENARIOS[norm_scenario]

    norm_model = str(model_name).strip().lower()
    if norm_model not in VALID_MODELS:
        raise ValueError(
            f"Invalid model_name '{model_name}'. Permissible options: "
            f"{sorted(list(VALID_MODELS))}."
        )

    return canonical_scenario, norm_model


# =============================================================================
# PUBLIC PREDICTION FUNCTION 1: Task B (Binary Anemia Screening)
# =============================================================================

def predict_anemia_screening(
    cbc_values: Dict[str, Any],
    scenario: str = "scenario_2",
    model_name: str = "random_forest",
) -> Dict[str, Any]:
    """
    Perform binary anemia screening on patient CBC blood test parameters.

    Classes:
      • 0 = Healthy (Non-Anemic)
      • 1 = Anemia Subtype (One of 5 anemia types: Iron deficiency, Normocytic hypochromic,
            Normocytic normochromic, Other microcytic, Macrocytic)

    Parameters
    ----------
    cbc_values : dict
        Mapping of exact 14 CBC features to numeric values.
    scenario : str
        'scenario_2' (default: conservative, excluded suspicious Category B rows),
        or 'scenario_1' (primary analysis).
    model_name : str
        'random_forest' (default), 'decision_tree', or 'logistic_regression'.

    Returns
    -------
    dict
        Prediction result containing predicted class (0 or 1), human-readable label,
        probability score, decision threshold applied, model metadata, and disclaimer.
    """
    # 1. Normalize configuration
    canon_scenario, canon_model = _normalize_config(scenario, model_name)
    metadata = get_model_metadata()
    model_key = f"task_b_{canon_scenario}_{canon_model}"

    if model_key not in metadata.get("models", {}):
        raise KeyError(f"Metadata key '{model_key}' not found in model_metadata.json.")
    meta_info = metadata["models"][model_key]

    # 2. Validate input CBC values
    df_features = validate_cbc_input(cbc_values)

    # 3. Load pipeline and predict
    pipeline = load_pipeline("task_b", canon_scenario, canon_model)

    # Retrieve decision threshold from metadata
    threshold = meta_info.get("tuned_threshold", 0.5)

    # Calculate class probabilities
    has_proba = hasattr(pipeline, "predict_proba")
    if has_proba:
        prob_array = pipeline.predict_proba(df_features)[0]
        # Class 1 is Anemia
        prob_anemia = float(prob_array[1])
        prob_healthy = float(prob_array[0])
        predicted_class = int(prob_anemia >= threshold)
    else:
        predicted_class = int(pipeline.predict(df_features)[0])
        prob_anemia = None
        prob_healthy = None

    screening_label = TASK_B_LABEL_MAPPING.get(predicted_class, f"Class {predicted_class}")

    return {
        "task": "Task B (Binary Anemia Screening)",
        "predicted_class": predicted_class,
        "screening_result": screening_label,
        "probability_anemia": round(prob_anemia, 4) if prob_anemia is not None else None,
        "probability_healthy": round(prob_healthy, 4) if prob_healthy is not None else None,
        "applied_threshold": float(threshold),
        "model_used": canon_model,
        "scenario": canon_scenario,
        "model_path": meta_info.get("model_path"),
        "training_rows": meta_info.get("train_rows"),
        "features_analyzed": EXPECTED_FEATURES,
        "clinical_disclaimer": CLINICAL_DISCLAIMER,
    }


# =============================================================================
# PUBLIC PREDICTION FUNCTION 2: Task A (Multiclass Diagnosis Classification)
# =============================================================================

def predict_diagnosis(
    cbc_values: Dict[str, Any],
    scenario: str = "scenario_2",
    model_name: str = "random_forest",
) -> Dict[str, Any]:
    """
    Perform 9-class multiclass diagnosis classification on patient CBC parameters.

    Target Classes (Original 9 dataset categories):
      1. Healthy
      2. Iron deficiency anemia
      3. Leukemia
      4. Leukemia with thrombocytopenia
      5. Macrocytic anemia
      6. Normocytic hypochromic anemia
      7. Normocytic normochromic anemia
      8. Other microcytic anemia
      9. Thrombocytopenia

    Parameters
    ----------
    cbc_values : dict
        Mapping of exact 14 CBC features to numeric values.
    scenario : str
        'scenario_2' (default), or 'scenario_1'.
    model_name : str
        'random_forest' (default), 'decision_tree', or 'logistic_regression'.

    Returns
    -------
    dict
        Prediction result containing predicted diagnosis label, class probabilities
        correctly mapped to all 9 original classes, model metadata, and disclaimer.
    """
    # 1. Normalize configuration
    canon_scenario, canon_model = _normalize_config(scenario, model_name)
    metadata = get_model_metadata()
    model_key = f"task_a_{canon_scenario}_{canon_model}"

    if model_key not in metadata.get("models", {}):
        raise KeyError(f"Metadata key '{model_key}' not found in model_metadata.json.")
    meta_info = metadata["models"][model_key]

    # 2. Validate input CBC values
    df_features = validate_cbc_input(cbc_values)

    # 3. Load pipeline and predict
    pipeline = load_pipeline("task_a", canon_scenario, canon_model)

    predicted_label = str(pipeline.predict(df_features)[0])

    # Extract probability distribution aligned with classifier classes
    class_probabilities: Optional[Dict[str, float]] = None
    if hasattr(pipeline, "predict_proba"):
        prob_array = pipeline.predict_proba(df_features)[0]
        classifier_classes = pipeline.named_steps["classifier"].classes_
        class_probabilities = {
            str(cls_name): round(float(prob_array[i]), 4)
            for i, cls_name in enumerate(classifier_classes)
        }

    return {
        "task": "Task A (Multiclass Diagnosis Classification)",
        "predicted_diagnosis": predicted_label,
        "class_probabilities": class_probabilities,
        "model_used": canon_model,
        "scenario": canon_scenario,
        "model_path": meta_info.get("model_path"),
        "training_rows": meta_info.get("train_rows"),
        "features_analyzed": EXPECTED_FEATURES,
        "rare_class_note": (
            "Note: Certain rare hematologic subtypes (e.g. Macrocytic anemia, "
            "Leukemia with thrombocytopenia) have small sample representations in the dataset. "
            "Output probabilities represent uncalibrated model scores interpreted as probabilities "
            "and must not be interpreted as absolute clinical risk."
        ),
        "clinical_disclaimer": CLINICAL_DISCLAIMER,
    }
